REPO_ROOT = Path(__file__).resolve().parent.parent
ARTIFACTS_DIR = REPO_ROOT / "artifacts"
RESULTS_DIR = REPO_ROOT / "results"
RANDOM_SEED = 42


def load_feature_cols() -> List[str]:
    """Loads feature column names from artifacts/feature_cols.json."""
    feat_path = ARTIFACTS_DIR / "feature_cols.json"
    with open(feat_path, "r", encoding="utf-8") as f:
        return json.load(f)


def load_candidate_data(max_train_trips: int = None) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    Loads candidate datasets generated by Saanvi Samayam:
    artifacts/features/train_cands.pkl and student_test_cands.pkl
    """
    features_dir = ARTIFACTS_DIR / "features"
    train_pkl = features_dir / "train_cands.pkl"
    test_pkl = features_dir / "student_test_cands.pkl"

    if not train_pkl.exists() or not test_pkl.exists():
        raise FileNotFoundError(
            f"Missing candidate files in {features_dir}. Run features/build_dataset.py first."
        )

    print(f"Loading {train_pkl}...")
    train_df = pd.read_pickle(train_pkl)
    print(f"Loading {test_pkl}...")
    test_df = pd.read_pickle(test_pkl)

    # Standardize column naming: ensure 'label' and 'y' are aligned
    if "y" in train_df.columns and "label" not in train_df.columns:
        train_df["label"] = train_df["y"]
    if "y" in test_df.columns and "label" not in test_df.columns:
        test_df["label"] = test_df["y"]

    if max_train_trips is not None and train_df["trip_id"].nunique() > max_train_trips:
        selected_trips = train_df["trip_id"].unique()[:max_train_trips]
        train_df = train_df[train_df["trip_id"].isin(selected_trips)].copy()
        print(f"Subsampled train to {max_train_trips} trips ({len(train_df)} candidate rows)")

    return train_df, test_df


def evaluate_model_cv(
    pipeline: Pipeline,
    train_df: pd.DataFrame,
    feature_cols: List[str],
    n_splits: int = 5
) -> Dict[str, Any]:
    """Performs 5-Fold GroupKFold Cross-Validation grouped by trip_id."""
    gkf = GroupKFold(n_splits=n_splits)
    groups = train_df["trip_id"].values
    X = train_df[feature_cols].values
    y = train_df["label"].values

    fold_f1s = []
    fold_top1s = []
    fold_log_losses = []
    train_times = []

    oof_probs = np.zeros(len(train_df), dtype=float)

    for fold, (train_idx, val_idx) in enumerate(gkf.split(X, y, groups=groups)):
        X_train, y_train = X[train_idx], y[train_idx]
        X_val, y_val = X[val_idx], y[val_idx]
        val_sub_df = train_df.iloc[val_idx].copy()

        t0 = time.time()
        pipeline.fit(X_train, y_train)
        fit_dur = time.time() - t0
        train_times.append(fit_dur)

        if hasattr(pipeline, "predict_proba"):
            probs = pipeline.predict_proba(X_val)
            val_probs = probs[:, 1] if probs.shape[1] > 1 else probs[:, 0]
        elif hasattr(pipeline, "decision_function"):
            df_vals = pipeline.decision_function(X_val)
            val_probs = 1.0 / (1.0 + np.exp(-df_vals))
        else:
            val_probs = pipeline.predict(X_val).astype(float)

        oof_probs[val_idx] = val_probs
        val_sub_df["prob"] = val_probs
        val_preds = (val_probs >= 0.5).astype(int)

        fold_f1 = macro_f1(y_val, val_preds)
        fold_top1 = top1_accuracy(val_sub_df, prob_col="prob")
        fold_ll = compute_log_loss(y_val, val_probs)

        fold_f1s.append(fold_f1)
        fold_top1s.append(fold_top1)
        fold_log_losses.append(fold_ll)

    train_df_oof = train_df.copy()
    train_df_oof["prob"] = oof_probs
    train_df_oof["pred"] = (oof_probs >= 0.5).astype(int)

    cv_results = {
        "cv_macro_f1_mean": float(np.mean(fold_f1s)),
        "cv_macro_f1_std": float(np.std(fold_f1s)),
        "cv_top1_acc_mean": float(np.mean(fold_top1s)),
        "cv_top1_acc_std": float(np.std(fold_top1s)),
        "cv_log_loss_mean": float(np.mean(fold_log_losses)),
        "cv_log_loss_std": float(np.std(fold_log_losses)),
        "cv_train_time_mean": float(np.mean(train_times)),
        "oof_df": train_df_oof
    }
    return cv_results


def evaluate_student_test(
    pipeline: Pipeline,
    test_df: pd.DataFrame,
    feature_cols: List[str]
) -> Dict[str, Any]:
    """Evaluates on 10 student-test trips and measures per-trip inference latency."""
    X_test = test_df[feature_cols].values
    y_test = test_df["label"].values

    t0 = time.time()
    if hasattr(pipeline, "predict_proba"):
        probs = pipeline.predict_proba(X_test)
        test_probs = probs[:, 1] if probs.shape[1] > 1 else probs[:, 0]
    elif hasattr(pipeline, "decision_function"):
        df_vals = pipeline.decision_function(X_test)
        test_probs = 1.0 / (1.0 + np.exp(-df_vals))
    else:
        test_probs = pipeline.predict(X_test).astype(float)
    total_infer_time = time.time() - t0

    n_trips = test_df["trip_id"].nunique()
    infer_time_per_trip = (total_infer_time / max(1, n_trips)) * 1000.0  # ms per trip

    test_eval_df = test_df.copy()
    test_eval_df["prob"] = test_probs
    test_eval_df["pred"] = (test_probs >= 0.5).astype(int)

    results = {
        "test_macro_f1": float(macro_f1(y_test, test_eval_df["pred"])),
        "test_top1_acc": float(top1_accuracy(test_eval_df, prob_col="prob")),
        "test_log_loss": float(compute_log_loss(y_test, test_probs)),
        "test_precision": float(precision(y_test, test_eval_df["pred"])),
        "test_recall": float(recall(y_test, test_eval_df["pred"])),
        "test_infer_time_ms_per_trip": float(infer_time_per_trip),
        "scored_test_df": test_eval_df
    }
    return results


def log_experiment(
    model_name: str,
    family: str,
    config_dict: Dict[str, Any],
    cv_metrics: Dict[str, Any],
    test_metrics: Dict[str, Any]
) -> None:
    """Appends an experimental run to results/experiments.csv."""
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    exp_file = RESULTS_DIR / "experiments.csv"

    row = {
        "timestamp": datetime.now().isoformat(),
        "model": model_name,
        "family": family,
        "config": json.dumps(config_dict),
        "seed": RANDOM_SEED,
        "cv_macro_f1_mean": round(cv_metrics.get("cv_macro_f1_mean", 0.0), 4),
        "cv_macro_f1_std": round(cv_metrics.get("cv_macro_f1_std", 0.0), 4),
        "cv_top1_acc_mean": round(cv_metrics.get("cv_top1_acc_mean", 0.0), 4),
        "cv_log_loss_mean": round(cv_metrics.get("cv_log_loss_mean", 0.0), 4),
        "test_macro_f1": round(test_metrics.get("test_macro_f1", 0.0), 4),
        "test_top1_acc": round(test_metrics.get("test_top1_acc", 0.0), 4),
        "test_log_loss": round(test_metrics.get("test_log_loss", 0.0), 4),
        "test_precision": round(test_metrics.get("test_precision", 0.0), 4),
        "test_recall": round(test_metrics.get("test_recall", 0.0), 4),
        "cv_train_time_mean_s": round(cv_metrics.get("cv_train_time_mean", 0.0), 3),
        "test_infer_ms_per_trip": round(test_metrics.get("test_infer_time_ms_per_trip", 0.0), 2)
    }

    df_row = pd.DataFrame([row])
    if exp_file.exists():
        df_row.to_csv(exp_file, mode="a", header=False, index=False)
    else:
        df_row.to_csv(exp_file, mode="w", header=True, index=False)
    print(f"Logged experiment for '{model_name}' to {exp_file}")
